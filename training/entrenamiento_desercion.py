"""MODELO A"""

import json
import os
import time
import numpy as np
import pandas as pd
import joblib
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPRegressor
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    confusion_matrix,
    f1_score,
    mean_squared_error,
    precision_recall_curve,
    r2_score,
    roc_auc_score,
)

EDAD_MINIMA = 15
CPV_ANIO = 2020
NIVACAD_MIN = 4
NIVACAD_MAX = 11
TEST_SIZE = 0.20
RANDOM_STATE = 42
N_SEMILLAS = 8
# Con 0.30 (valor original) el umbral salía tan bajo (~0.057) que casi
# cualquier caso se marcaba "en riesgo": 98% de recall pero 86,702 falsos
# positivos contra 37,158 verdaderos positivos (accuracy 59.5%). Se sube a
# 0.45 para exigir más precisión al modelo, aunque eso baje algo el recall;
# ajusta este valor según qué tan tolerante quieras que sea el sistema a
# falsos positivos vs. casos de riesgo no detectados.
PRECISION_OBJETIVO = 0.60

# Variables que se piden en el formulario / vienen del CSV.
VARIABLES_RECOLECTADAS = [
    "ENT", "MUN", "SEXO", "EDAD", "SERSALUD", "PERTE_INDIGENA", "NACIONALIDAD",
    "ASISTEN", "ESCOLARI", "NIVACAD", "ESCOACUM", "SITUA_CONYUGAL",
    "SITUACION_TRAB", "COMPUTADORA", "CELULAR", "INTERNET", "INGTRHOG",
    "TAMLOC", "CPV",
]

# ASISTEN, NIVACAD y ESCOACUM se excluyen como PREDICTORES por fuga de datos:
# son las variables con las que el propio INEGI calculó DES, así que dejarlas
# como entrada del modelo permite "adivinar" la respuesta en vez de predecirla.
# Se siguen recolectando (NIVACAD se usa DESPUÉS de la predicción, ver
# clasificar_nivel_riesgo), igual que en permanencia_educativa y
# desercion_escolar.
VARIABLES_EXCLUIDAS_FUGA = ["ASISTEN", "NIVACAD", "ESCOACUM"]
VARIABLES_ENTRADA = [v for v in VARIABLES_RECOLECTADAS if v not in VARIABLES_EXCLUIDAS_FUGA]

VARIABLE_SALIDA_ORIGINAL = "DES"      # 0 / 5 / 9, tal como viene del censo
VARIABLE_SALIDA_BINARIA = "EN_RIESGO"  # 0.0 / 1.0, derivado de DES != 0

# Regla NIVACAD -> tipo de riesgo (medio superior / superior). NIVACAD no
# entra al modelo; solo se usa después de la predicción para describir el
# tipo de deserción, igual que en los otros dos proyectos.
NIVELES_MEDIO_SUPERIOR = [4, 5, 6, 7, 8, 9]
NIVELES_SUPERIOR = [10, 11]

RUTA_MODELO_A = "modelo_desercion_mlp.joblib"
RUTA_SCALER_A = "scaler_desercion.joblib"
RUTA_METADATA_A = "model_metadata.json"


def cargar_y_limpiar_datos_A(ruta_csv: str) -> pd.DataFrame:
    print(f"Cargando {ruta_csv} ...")
    columnas = VARIABLES_RECOLECTADAS + [VARIABLE_SALIDA_ORIGINAL]
    df = pd.read_csv(ruta_csv, usecols=columnas, encoding="utf-8-sig")
    print(f"  Registros totales leidos: {len(df):,}")
    df = df[columnas]

    antes = len(df); df = df.dropna()
    print(f"  Eliminados por valores vacios: {antes - len(df):,}")

    antes = len(df); df = df.drop_duplicates()
    print(f"  Eliminados por duplicados: {antes - len(df):,}")

    antes = len(df); df = df[df["EDAD"] >= EDAD_MINIMA]
    print(f"  Eliminados por EDAD >= {EDAD_MINIMA}: {antes - len(df):,}")

    antes = len(df); df = df[df["CPV"] == CPV_ANIO]
    print(f"  Eliminados por CPV != {CPV_ANIO}: {antes - len(df):,}")

    antes = len(df); df = df[(df["NIVACAD"] >= NIVACAD_MIN) & (df["NIVACAD"] <= NIVACAD_MAX)]
    print(f"  Eliminados por NIVACAD [{NIVACAD_MIN}-{NIVACAD_MAX}]: {antes - len(df):,}")

    antes = len(df); df = df[df["ESCOACUM"] != 99]
    print(f"  Eliminados por ESCOACUM == 99: {antes - len(df):,}")

    antes = len(df); df = df[df["INGTRHOG"] < 999998]
    print(f"  Eliminados por INGTRHOG >= 999998: {antes - len(df):,}")

    print(f"  Registros finales: {len(df):,}")
    valores_des = sorted(df[VARIABLE_SALIDA_ORIGINAL].unique().tolist())
    print(f"  Valores unicos en DES: {valores_des}")
    if set(valores_des) != {0, 5, 9} and set(valores_des) != {1, 3, 9}:
        print("  ADVERTENCIA: los valores de DES no coinciden con lo esperado.")
    return df


def verificar_regla_nivacad(df: pd.DataFrame) -> None:
    """Confirma que NIVACAD -> tipo de deserción sea una correspondencia pura
    antes de usarla como regla fija de post-proceso (igual que en
    permanencia_educativa / desercion_escolar)."""
    desertores = df[df[VARIABLE_SALIDA_ORIGINAL].isin([5, 9])]
    tabla = pd.crosstab(desertores["NIVACAD"], desertores[VARIABLE_SALIDA_ORIGINAL])
    mezclados = tabla.astype(bool).sum(axis=1) > 1
    if mezclados.any():
        print("  ADVERTENCIA: NIVACAD mezcla DES=5 y DES=9 en:",
              tabla.index[mezclados].tolist())
    else:
        print("  Verificación NIVACAD -> tipo de deserción: OK, correspondencia pura.")


def elegir_umbral(y_true, proba, precision_objetivo: float) -> float:
    """Sobre la curva precision-recall, busca el umbral de mayor recall que
    alcanza la precisión objetivo (misma lógica que los otros dos modelos)."""
    precisiones, recalls, umbrales = precision_recall_curve(y_true, proba)
    precisiones, recalls = precisiones[:-1], recalls[:-1]
    candidatos = np.where(precisiones >= precision_objetivo)[0]
    if len(candidatos) == 0:
        print(f"  AVISO: precisión objetivo {precision_objetivo:.2f} no alcanzable "
              f"(máximo posible {precisiones.max():.4f}). Se usa umbral 0.5 por defecto.")
        return 0.5
    mejor_idx = candidatos[np.argmax(recalls[candidatos])]
    print(f"  Umbral elegido: {umbrales[mejor_idx]:.3f} "
          f"(precisión={precisiones[mejor_idx]:.4f}, recall={recalls[mejor_idx]:.4f})")
    return float(umbrales[mejor_idx])


df_A = cargar_y_limpiar_datos_A(RUTA_CSV)
verificar_regla_nivacad(df_A)

X = df_A[VARIABLES_ENTRADA].values
# DES deja de regresarse tal cual (0/5/9); se colapsa a EN_RIESGO (0.0/1.0),
# igual que TARGET_BINARIO en los otros dos modelos. El MLPRegressor sigue
# siendo una regresión: predice un puntaje continuo que se interpreta como
# una probabilidad de riesgo.
y = (df_A[VARIABLE_SALIDA_ORIGINAL] != 0).astype(float).values

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y
)
print(f"\nEntrenamiento: {len(X_train):,} | Prueba: {len(X_test):,}")
print(f"Variables usadas como predictor ({len(VARIABLES_ENTRADA)}): {VARIABLES_ENTRADA}")
print(f"Variables excluidas por fuga de datos: {VARIABLES_EXCLUIDAS_FUGA}")

scaler = MinMaxScaler()
X_train_esc = scaler.fit_transform(X_train)
X_test_esc = scaler.transform(X_test)

mejor_modelo, mejor_f1 = None, -np.inf
print(f"\nProbando {N_SEMILLAS} inicializaciones aleatorias...")
for i in range(N_SEMILLAS):
    semilla = RANDOM_STATE + i
    modelo = MLPRegressor(
        hidden_layer_sizes=(2, 2, 2, 2), activation="relu", solver="adam",
        alpha=0.001, max_iter=5000, random_state=semilla,
    )
    inicio = time.time()
    modelo.fit(X_train_esc, y_train)
    duracion = time.time() - inicio
    pred_test = np.clip(modelo.predict(X_test_esc), 0.0, 1.0)
    # Selección de semilla por F1 (clasificación binaria a 0.5), no por R^2:
    # lo que importa ahora es qué tan bien separa en_riesgo / no_riesgo.
    f1_05 = f1_score(y_test, (pred_test >= 0.5).astype(int))
    print(f"  Semilla {semilla}: {modelo.n_iter_} iteraciones, {duracion:.1f}s, F1@0.5 = {f1_05:.4f}")
    if f1_05 > mejor_f1:
        mejor_f1, mejor_modelo = f1_05, modelo

print(f"\nMejor semilla: F1@0.5 = {mejor_f1:.4f}")

y_pred_continuo = np.clip(mejor_modelo.predict(X_test_esc), 0.0, 1.0)

print("\n--- Ajuste como regresión (sobre EN_RIESGO 0/1) ---")
print(f"R^2: {r2_score(y_test, y_pred_continuo):.6f}")
print(f"MSE: {mean_squared_error(y_test, y_pred_continuo):.6f}")

umbral = elegir_umbral(y_test, y_pred_continuo, PRECISION_OBJETIVO)
y_pred_clase = (y_pred_continuo >= umbral).astype(int)

acc = accuracy_score(y_test, y_pred_clase)
bal_acc = balanced_accuracy_score(y_test, y_pred_clase)
f1 = f1_score(y_test, y_pred_clase)
auc = roc_auc_score(y_test, y_pred_continuo)
cm = confusion_matrix(y_test, y_pred_clase, labels=[0, 1])

print("\n--- Resultados como clasificación (en_riesgo / no_riesgo) ---")
print(f"Accuracy:          {acc:.4%}")
print(f"Balanced accuracy: {bal_acc:.4f}")
print(f"F1:                {f1:.4f}")
print(f"ROC-AUC:           {auc:.4f}")
print("Matriz de confusión, orden [0, 1]:")
print(cm)

joblib.dump(mejor_modelo, RUTA_MODELO_A)
joblib.dump(scaler, RUTA_SCALER_A)

metadata = {
    "model_type": "MLPRegressor (hidden_layer_sizes=(2,2,2,2)) usado como clasificador binario vía umbral",
    "target": VARIABLE_SALIDA_BINARIA,
    "target_derivation": "EN_RIESGO = 1.0 si DES != 0 (fusiona DES=5 y DES=9), 0.0 si DES == 0",
    "features": VARIABLES_ENTRADA,
    "features_collected_but_excluded": VARIABLES_EXCLUIDAS_FUGA,
    "leakage_note": (
        "ASISTEN, NIVACAD y ESCOACUM se siguen recolectando en el formulario "
        "pero no se usan como predictor porque son las variables con las que "
        "DES fue calculada originalmente. NIVACAD se usa DESPUÉS de la "
        "predicción para describir el tipo de riesgo (ver "
        "nivacad_subclassification_rule)."
    ),
    "decision_threshold": umbral,
    "threshold_note": (
        "Se predice 'en_riesgo' si el valor continuo del MLPRegressor "
        "(acotado a [0,1]) es >= decision_threshold, buscando una precisión "
        f"mínima objetivo de {PRECISION_OBJETIVO:.2f} maximizando el recall."
    ),
    "nivacad_subclassification_rule": {
        "nivel_medio_superior": NIVELES_MEDIO_SUPERIOR,
        "nivel_superior": NIVELES_SUPERIOR,
    },
    "train_rows": int(len(X_train)),
    "test_rows": int(len(X_test)),
    "metrics": {
        "r2": float(r2_score(y_test, y_pred_continuo)),
        "mse": float(mean_squared_error(y_test, y_pred_continuo)),
        "accuracy": float(acc),
        "balanced_accuracy": float(bal_acc),
        "f1": float(f1),
        "roc_auc": float(auc),
    },
    "sklearn_version": __import__("sklearn").__version__,
}
with open(RUTA_METADATA_A, "w", encoding="utf-8") as f:
    json.dump(metadata, f, ensure_ascii=False, indent=2)

print(f"\nGuardados: {RUTA_MODELO_A}, {RUTA_SCALER_A}, {RUTA_METADATA_A}")

